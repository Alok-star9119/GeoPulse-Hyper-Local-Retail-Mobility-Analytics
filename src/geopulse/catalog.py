"""Day 16: a generated catalogue of every result table (columns and sizes), for the data dictionary."""
from __future__ import annotations

import re
from pathlib import Path

import pandas as pd


def pattern(name: str) -> str:
    """'hub_rhythm_stats_2024-01.csv' -> 'hub_rhythm_stats_{month}.csv'."""
    return re.sub(r"\d{4}-\d{2}", "{month}", name)


def build_catalog(tables: Path) -> pd.DataFrame:
    groups: dict[str, list[Path]] = {}
    for f in sorted(Path(tables).glob("*.csv")):
        groups.setdefault(pattern(f.name), []).append(f)
    rows = []
    for pat, files in groups.items():
        head = pd.read_csv(files[0], nrows=0)
        n_rows = sum(max(sum(1 for _ in open(f, encoding="utf-8")) - 1, 0) for f in files)
        rows.append({"table": pat, "files": len(files), "rows_total": n_rows, "columns": ", ".join(head.columns)})
    return pd.DataFrame(rows, columns=["table", "files", "rows_total", "columns"])


def render(cat: pd.DataFrame) -> str:
    L = ["# Table Catalog (generated)", "",
         "Every CSV in `reports/tables/`, grouped by name (`{month}` = one file per month). Generated by "
         "`scripts/build_table_catalog.py`; do not edit by hand. Meaning of columns: see `data_dictionary.md`.", ""]
    if cat.empty:
        return "\n".join(L + ["No tables found yet.", ""])
    L += ["| Table | Files | Rows (all files) | Columns |", "|---|---|---|---|"]
    L += [f"| `{r.table}` | {r.files} | {r.rows_total:,} | {r.columns} |" for r in cat.itertuples()]
    return "\n".join(L + [""])
